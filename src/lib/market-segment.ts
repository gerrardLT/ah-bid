/**
 * 「其他」的细分规则（只对 typeOfTitle 认不出的标题生效）。
 *
 * 为什么单独一个文件、为什么不能改 TYPE_KW：
 *   typeOfTitle 有 6 个消费者（collectPairs / price-ref / price-benchmark /
 *   tech-bid / control-price / agg-build），改一个词会让 410 个价格配对重新分类，
 *   而四道质量闸门**没有一条检查分类分布** —— 改坏了发现不了。
 *   实测：把「改造」加进房建会让 28 条配对从其他进房建（168→196），
 *   房建中位从 18.7% 漂移。
 *
 * 所以本表只在 `typeOfTitle(t) === '其他'` 时生效，构造上不可能改动
 * 已经在房建/市政/水利…的样本。验收标准也因此可判定：
 * **其余 8 类计数必须逐类相等，只有「其他」变小。**
 *
 * 入表铁律：只收 ≥3 字的复合词。
 * 禁止入表：改造、中心、基地 —— 实测「改造」的 83 条命中里 28 条是其他、
 * 1 条是市政；「中心」跨房建/智能化（数据中心）/体育中心三类。
 * 加进去只是把一个误判换成三个。
 */

export interface SegmentRule {
  /** 归属的行业（只能是 typeOfTitle 已有的 8 类之一） */
  seg: string;
  /** 命中任一即归入，按数组顺序先命中先用 */
  kw: string[];
  /** 这批词的实测条数，写在注释里方便以后判断收益 */
}

/**
 * 顺序有讲究：农村公路放最前，因为「XX公路提质改造」也含「提质改造」，
 * 而它属于公路不是房建。
 */
export const SEGMENT_RULES: SegmentRule[] = [
  // 实测 315 条：农村公路养护/提质改造/县乡道/联网路
  { seg: '市政', kw: ['农村公路', '县乡道', '联网路', '公路养护', '公路提质', '村道'] },
  // 实测 161 条：和美乡村/中心村/示范村/人居环境
  { seg: '市政', kw: ['和美乡村', '中心村', '示范村', '人居环境', '美丽乡村', '村庄整治'] },
  // 实测 41 条：场馆/综合体（「服务中心」不入表 —— 数据中心是智能化）
  { seg: '房建', kw: ['场馆', '综合体', '体育馆', '文化馆', '科技馆'] },
  // 实测 23 条：管网/排涝/雨污分流（「广场」不入表 —— 可能是房建也可能是市政）
  { seg: '市政', kw: ['管网', '排涝', '雨污分流', '污水治理', '易涝点'] },
];

/** 返回 null 表示这条规则不认领，继续用「其他」/「未分类」 */
export function segmentOf(title: string): string | null {
  for (const r of SEGMENT_RULES) {
    for (const k of r.kw) {
      if (title.includes(k)) return r.seg;
    }
  }
  return null;
}
